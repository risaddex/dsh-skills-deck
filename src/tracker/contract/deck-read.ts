/**
 * src/tracker/contract/deck-read.ts —— 手机只读面板两条读的上限数字，全仓唯一一份（规格 #70、票 #73）。
 *
 * 为什么要单开这一个文件：这两个条数与一道字节上限被**两处**读者同时需要 —— 今天的树投影
 * （src/host/deckTree.ts）与票读（src/host/deckTicket.ts），以及 #74 之后把回包转给手机的那条
 * 远程通道。三处各写一遍就是三个可以各自漂移的真源：改小一处，另一处照旧回一份更大的树，
 * 面板上看到的就是「这一屏比以前少了一半容器」而没有任何东西会红。收在这里以后，谁要用就 import
 * 同一个名字；改数字是一次能被人看见的 diff。
 *
 * 为什么住契约层、而不是宿主层的某个文件：契约层是「房间与 deck 唯一可以深引的公共面」
 * （.dependency-cruiser.ts 的 deck-deep-import 规则），所以将来的 deck 侧通道可以直接引它；
 * 宿主与 deck 引同一个名字，不需要再为「宿主层的数字能不能给 deck 用」另开一条豁免。
 *
 * 三个数字的来历要分清（票 #73 的原话：规格只钉了两个条数）：
 *  · maxContainers = 50、maxTickets = 200 是**规格 #70 自己钉的条数**，不是这里挑的安全值：
 *    一张手机屏只画得下一屏容器，一屏容器再带两百张票已经够点到为止；改它要回去改规格，
 *    不是改这一行就完事。
 *  · maxProjectionBytes 规格没写，是**本票补的传输护栏**：只挡住了「条数没超但单票正文特别大」
 *    这一类（例如一张 5 MB 的票），让手机那头的通道不至于被一个回包撑爆。选 256 KiB（262144 字节）
 *    的理由是它比「50 个容器 + 200 张票」的正常投影（实测量级在几十 KB）宽出一个数量级，
 *    正常仓库永远不会撞上它，撞上就是一个真该失败的异常。
 *
 * 边界：这里只有数字，没有任何行为（契约目录只许放类型与数据，见 tests/verify-contract-types.ts）。
 * 三个数都不搬进 config/ 下的 YAML：条数、页数这类值按 docs/adr/20261016-time-config-yaml.md 第 5 节
 * 明确排除在外，它们是安全护栏而不是给人调的旋钮（同一口径见 contract/pagination.ts 的文件头）。
 */
export const DECK_READ_LIMITS = {
  /** 树投影最多带几个容器（规格 #70 钉的条数）。 */
  maxContainers: 50,
  /** 树投影最多带几张票（规格 #70 钉的条数，跨容器合计）。 */
  maxTickets: 200,
  /** 一次回包的投影 JSON 最多多少字节；超了就如实失败，绝不回半份（本票补的传输护栏）。 */
  maxProjectionBytes: 262144,
} as const
