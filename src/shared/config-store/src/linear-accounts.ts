/**
 * src/shared/config-store/src/linear-accounts.ts —— Linear account metadata (map ticket #12)
 *
 * Pure functions, no filesystem. File: `<home>/.dsh/mattskillsdeck/linear-accounts.yaml`, version 1.
 *
 * Why this is its own data file rather than a section of settings.yaml (the decision this module
 * carries out): an account is user data edited by the user, and it is semantically rich — an alias
 * grammar, uniqueness, a pinned organization, team filters and a review-state pattern. settings.yaml
 * is the strict scalar/switch store for view preferences and has no nested-list shape; forcing the
 * accounts in there would put the same validator in two units (settings.ts is documented as
 * self-contained and may not import this file), and one malformed alias would then take every view
 * preference down with it. `docs/agents/label-colors.yaml` already set this precedent: user data
 * that the plugin owns live in a file of its own, beside settings.yaml.
 *
 * The secrets are never here. This document holds only what is safe to render on screen: which
 * accounts exist, what they are called, and how each one authenticates. The token for an account
 * lives in the DSH credential store as the record `<scope>/linear-<alias>`, written only through
 * `ctx.credentials.modifyRecord`; section C of research/12-linear-accounts-facts.md records why.
 *
 * Self-contained: this unit writes its own small helpers and imports nothing but the YAML parser and
 * its own port types (same rule as labels.ts, which this file is modelled on).
 */

import type { ConfigParseResult, ConfigStringifyResult } from './ports.js'

/** Where the file sits under the harness home (the caller joins the segments; the core never touches home). */
export const LINEAR_ACCOUNTS_REL_SEGMENTS = ['.dsh', 'mattskillsdeck', 'linear-accounts.yaml']
/** Version this core understands; a newer version is read-only, anything else is a bad shape. */
const LINEAR_ACCOUNTS_KNOWN_VERSION = 1
/** Alias grammar, inherited from the registry this fork replaces: lowercase, digits and hyphens, 2–16 characters. It also satisfies the credential-record id grammar `^[a-z][a-z0-9-]*$`, so `linear-<alias>` is always a legal record id. */
const LINEAR_ALIAS_PATTERN = /^[a-z][a-z0-9-]{1,15}$/
/** How an account authenticates. `oauth_app` is the actor=app installation; see research/12-linear-signin-protocol.md. */
const LINEAR_AUTH_TYPES = ['api_key', 'oauth_user', 'oauth_app']
/** Which issues count as "needs review" for this account. `subscribed` is someone else's work I follow. */
const LINEAR_REVIEW_SCOPES = ['subscribed', 'team', 'assigned']
/** Default review-state name pattern, kept verbatim from the plugin this fork replaces. */
const LINEAR_DEFAULT_REVIEW_PATTERN = 'review|revisando|revisão|revisao|qa'
/** Guard rails: a real person has a handful of workspaces, not hundreds. */
const MAX_LINEAR_ACCOUNTS = 20

const HEADER = ['# Comments in this file are generated by the plugin; your own comments will be replaced on the next write.', '# It holds no secret: each account names how it authenticates, and the token itself lives in the DSH credential store.']
const COMMENT_VERSION = '# Data version (a newer version unknown to the core is read-only)'
const COMMENT_DEFAULT = "# Alias used by calls that do not name an account ('' = none)"
const COMMENT_ACCOUNTS = '# The Linear workspaces this machine knows about'
const DOC_KEYS = ['version', 'defaultAccount', 'accounts']
const ACCOUNT_KEYS = ['alias', 'label', 'authType', 'orgId', 'urlKey', 'teams', 'reviewPattern', 'reviewScope', 'previousAliases']
const PREVIOUS_KEYS = ['alias', 'until']

/** One account as it is stored and read back. Every field is always present after normalization. */
export interface LinearAccountRecord {
  alias: string
  label: string
  authType: string
  orgId: string
  urlKey: string
  teams: string[]
  reviewPattern: string
  reviewScope: string
  previousAliases: Array<{ alias: string; until: string }>
}

/** The whole document, normalized. */
export interface LinearAccountsDoc {
  version: number
  defaultAccount: string
  accounts: LinearAccountRecord[]
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v)
}

function isInt(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v)
}

/** A name that would walk the prototype chain is never a usable key. */
function isDangerousKey(key: string): boolean {
  return key === '__proto__' || key === 'constructor' || key === 'prototype'
}

/** The two failure shapes this file can produce; a subset of the port's ParseFailReason, so the same value feeds both a section parse and a whole-document parse. */
type FailResult = { ok: false; reason: 'bad-shape' | 'unknown-keys'; message: string; keys?: string[] }

function fail(reason: 'bad-shape' | 'unknown-keys', message: string, keys?: string[]): FailResult {
  return keys ? { ok: false, reason, message, keys } : { ok: false, reason, message }
}

/** One account, normalized, or the reason it could not be. Kept apart from ConfigParseResult because the value here is a concrete account, not the loose document a file parses into. */
type NormalizeAccountResult = { ok: true; value: LinearAccountRecord } | FailResult

/** Write a YAML scalar: bare only when it is unambiguously a word, double-quoted otherwise. */
function esc(text: string): string {
  if (text === '') return "''"
  const lower = text.toLowerCase()
  if (/^[A-Za-z_][A-Za-z0-9_\-]*$/.test(text) && lower !== 'yes' && lower !== 'no' && lower !== 'y' && lower !== 'n' && lower !== 'on' && lower !== 'off' && lower !== 'true' && lower !== 'false' && lower !== 'null' && lower !== '~') {
    return text
  }
  return (
    '"' +
    text
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\t/g, '\\t') +
    '"'
  )
}

/**
 * Normalize one account entry. Unknown field names are refused (silently dropping a name the user
 * typed loses data), scalar fields are type-checked, and the lists are cleaned the way the old
 * registry cleaned them: teams uppercased and deduplicated, expired or unusable previous aliases
 * dropped with a warning instead of failing the whole file.
 */
function normalizeAccount(raw: Record<string, unknown>, index: number, today: string, warnings: string[]): NormalizeAccountResult {
  const where = 'account #' + (index + 1)
  const strange = Object.keys(raw).filter((k) => ACCOUNT_KEYS.indexOf(k) < 0)
  if (strange.length > 0) return fail('unknown-keys', where + ' has fields unknown to the core: ' + strange.join(', '), strange)

  const aliasRaw = raw['alias']
  if (typeof aliasRaw !== 'string') return fail('bad-shape', where + ' needs an alias (the short name every Linear reference starts with)')
  const alias = aliasRaw.trim().toLowerCase()
  if (!LINEAR_ALIAS_PATTERN.test(alias)) {
    return fail('bad-shape', where + ' has an unusable alias \'' + aliasRaw + '\': use 2 to 16 lowercase letters, digits or hyphens, starting with a letter')
  }

  for (const key of ['label', 'orgId', 'urlKey', 'reviewPattern', 'reviewScope', 'authType']) {
    if (raw[key] !== undefined && typeof raw[key] !== 'string') return fail('bad-shape', where + ' (' + alias + ') field ' + key + ' must be text')
  }

  const authType = raw['authType'] === undefined ? 'api_key' : String(raw['authType'])
  if (LINEAR_AUTH_TYPES.indexOf(authType) < 0) {
    return fail('bad-shape', where + ' (' + alias + ') must have authType set to one of ' + LINEAR_AUTH_TYPES.join(', ') + ', received: ' + authType)
  }
  const reviewScope = raw['reviewScope'] === undefined ? 'subscribed' : String(raw['reviewScope'])
  if (LINEAR_REVIEW_SCOPES.indexOf(reviewScope) < 0) {
    return fail('bad-shape', where + ' (' + alias + ') must have reviewScope set to one of ' + LINEAR_REVIEW_SCOPES.join(', ') + ', received: ' + reviewScope)
  }
  const reviewPattern = raw['reviewPattern'] === undefined ? LINEAR_DEFAULT_REVIEW_PATTERN : String(raw['reviewPattern'])
  try {
    void new RegExp(reviewPattern, 'i')
  } catch (e) {
    return fail('bad-shape', where + ' (' + alias + ') has a reviewPattern that is not a usable regular expression: ' + reviewPattern)
  }

  const teamsRaw = raw['teams'] === undefined ? [] : raw['teams']
  let teams: string[] = []
  if (!Array.isArray(teamsRaw)) {
    warnings.push(where + ' (' + alias + '): teams must be a list of team keys, so it was ignored')
  } else {
    const seen: Record<string, boolean> = {}
    for (const item of teamsRaw) {
      if (typeof item !== 'string' || item.trim() === '') {
        warnings.push(where + ' (' + alias + '): an empty or non-text team key was ignored')
        continue
      }
      const key = item.trim().toUpperCase()
      if (seen[key] === true) continue
      seen[key] = true
      teams.push(key)
    }
  }

  const previousRaw = raw['previousAliases'] === undefined ? [] : raw['previousAliases']
  const previousAliases: Array<{ alias: string; until: string }> = []
  if (!Array.isArray(previousRaw)) {
    warnings.push(where + ' (' + alias + '): previousAliases must be a list, so it was ignored')
  } else {
    for (const item of previousRaw) {
      if (!isRecord(item)) {
        warnings.push(where + ' (' + alias + '): a previousAliases entry that is not a mapping was ignored')
        continue
      }
      const oldAlias = typeof item['alias'] === 'string' ? String(item['alias']).trim().toLowerCase() : ''
      const until = typeof item['until'] === 'string' ? String(item['until']).trim() : ''
      if (!LINEAR_ALIAS_PATTERN.test(oldAlias)) {
        warnings.push(where + ' (' + alias + '): a previous alias that is not a usable name was ignored')
        continue
      }
      if (!/^\d{4}-\d{2}-\d{2}$/.test(until)) {
        warnings.push(where + ' (' + alias + '): previous alias ' + oldAlias + ' was ignored because its until date is not YYYY-MM-DD')
        continue
      }
      if (until < today) {
        warnings.push(where + ' (' + alias + '): previous alias ' + oldAlias + ' expired on ' + until + ' and was ignored')
        continue
      }
      previousAliases.push({ alias: oldAlias, until })
    }
  }

  const label = raw['label'] === undefined || String(raw['label']).trim() === '' ? alias : String(raw['label']).trim()
  return {
    ok: true,
    value: {
      alias,
      label,
      authType,
      orgId: raw['orgId'] === undefined ? '' : String(raw['orgId']).trim(),
      urlKey: raw['urlKey'] === undefined ? '' : String(raw['urlKey']).trim(),
      teams,
      reviewPattern,
      reviewScope,
      previousAliases,
    },
  }
}

/** Validate one parsed document. */
export function parseLinearAccounts(doc: unknown, today?: string): ConfigParseResult {
  const day = typeof today === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(today) ? today : '0000-00-00'
  if (!isRecord(doc)) return fail('bad-shape', 'the Linear accounts file must be a name-to-value mapping, not a list or text')
  const strange = Object.keys(doc).filter((k) => DOC_KEYS.indexOf(k) < 0)
  if (strange.length > 0) return fail('unknown-keys', 'the Linear accounts file has fields unknown to the core: ' + strange.join(', '), strange)
  if (!isInt(doc['version'])) return fail('bad-shape', 'version in the Linear accounts file must be numeric')
  const version = doc['version'] as number
  if (version > LINEAR_ACCOUNTS_KNOWN_VERSION) {
    return {
      ok: true,
      value: doc,
      readonly: true,
      warnings: ['version-newer: this file has version ' + version + ', but the core only understands version 1; it may be displayed but must not be written back. Upgrade the plugin.'],
    }
  }
  if (version !== LINEAR_ACCOUNTS_KNOWN_VERSION) return fail('bad-shape', 'version in the Linear accounts file must be 1')

  if (doc['defaultAccount'] !== undefined && typeof doc['defaultAccount'] !== 'string') {
    return fail('bad-shape', 'defaultAccount in the Linear accounts file must be text (the alias a call uses when it names none)')
  }
  const accountsRaw = doc['accounts'] === undefined ? [] : doc['accounts']
  if (!Array.isArray(accountsRaw)) return fail('bad-shape', 'accounts in the Linear accounts file must be a list')
  if (accountsRaw.length > MAX_LINEAR_ACCOUNTS) {
    return fail('bad-shape', 'the Linear accounts file lists ' + accountsRaw.length + ' accounts, more than the ' + MAX_LINEAR_ACCOUNTS + ' the core accepts (this file is not meant to hold a whole directory)')
  }

  const warnings: string[] = []
  const accounts: LinearAccountRecord[] = []
  const aliasSeen: Record<string, boolean> = {}
  const orgSeen: Record<string, string> = {}
  for (let i = 0; i < accountsRaw.length; i += 1) {
    const entry = accountsRaw[i]
    if (!isRecord(entry)) return fail('bad-shape', 'account #' + (i + 1) + ' in the Linear accounts file must be a mapping')
    if (Object.keys(entry).some(isDangerousKey)) return fail('bad-shape', 'account #' + (i + 1) + ' in the Linear accounts file uses a name that is not allowed: ' + Object.keys(entry).filter(isDangerousKey).join(', '))
    const one = normalizeAccount(entry, i, day, warnings)
    if (one.ok !== true) return one
    const account = one.value
    if (aliasSeen[account.alias] === true) {
      return fail('bad-shape', 'two accounts in the Linear accounts file use the alias \'' + account.alias + '\'; an alias must be unique because every reference starts with it')
    }
    aliasSeen[account.alias] = true
    if (account.orgId !== '') {
      const owner = orgSeen[account.orgId]
      if (owner !== undefined) {
        return fail('bad-shape', 'accounts \'' + owner + '\' and \'' + account.alias + '\' both pin Linear organization ' + account.orgId + '; one organization belongs to one account')
      }
      orgSeen[account.orgId] = account.alias
    }
    accounts.push(account)
  }

  let defaultAccount = doc['defaultAccount'] === undefined ? '' : String(doc['defaultAccount']).trim().toLowerCase()
  if (defaultAccount === 'none' || defaultAccount === 'null') defaultAccount = ''
  if (defaultAccount !== '' && aliasSeen[defaultAccount] !== true) {
    warnings.push('defaultAccount names \'' + defaultAccount + '\', which is not one of the accounts in this file, so no default is set')
    defaultAccount = ''
  }

  return { ok: true, value: { version: 1, defaultAccount, accounts } as unknown as Record<string, unknown>, readonly: false, warnings }
}

/** Render one document. Re-validates through parseLinearAccounts, so what is written is always a complete template. */
export function stringifyLinearAccounts(value: unknown): ConfigStringifyResult {
  if (!isRecord(value)) return { ok: false, reason: 'bad-shape', message: 'the Linear accounts to write must be a name-to-value mapping' }
  const check = parseLinearAccounts(value)
  if (check.ok !== true) {
    return { ok: false, reason: check.reason === 'unknown-keys' ? 'unknown-keys' : 'bad-shape', message: check.message, keys: check.keys }
  }
  const doc = check.value as unknown as LinearAccountsDoc
  const lines: string[] = [...HEADER]
  lines.push(COMMENT_VERSION)
  lines.push('version: 1')
  lines.push(COMMENT_DEFAULT)
  lines.push('defaultAccount: ' + esc(doc.defaultAccount))
  lines.push(COMMENT_ACCOUNTS)
  if (doc.accounts.length === 0) {
    lines.push('accounts: []')
  } else {
    lines.push('accounts:')
    for (const account of doc.accounts) {
      lines.push('  - alias: ' + esc(account.alias))
      lines.push('    label: ' + esc(account.label))
      lines.push('    authType: ' + esc(account.authType))
      lines.push('    orgId: ' + esc(account.orgId))
      lines.push('    urlKey: ' + esc(account.urlKey))
      if (account.teams.length === 0) {
        lines.push('    teams: []')
      } else {
        lines.push('    teams: [' + account.teams.map(esc).join(', ') + ']')
      }
      lines.push('    reviewPattern: ' + esc(account.reviewPattern))
      lines.push('    reviewScope: ' + esc(account.reviewScope))
      if (account.previousAliases.length === 0) {
        lines.push('    previousAliases: []')
      } else {
        lines.push('    previousAliases:')
        for (const previous of account.previousAliases) {
          lines.push('      - alias: ' + esc(previous.alias))
          lines.push('        until: ' + esc(previous.until))
        }
      }
    }
  }
  return { ok: true, text: lines.join('\n') + '\n' }
}