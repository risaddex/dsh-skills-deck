/**
 * src/shared/config-store/src/labels.ts —— 标签配色数据的校验与拼装（#1012）
 *
 * 纯函数，不碰文件系统。文件：`docs/agents/label-colors.yaml`（版本 1；
 * 兼容读老 `label-colors.json`，老文件没有版本，当 1 读）。
 * 它是数据不是配置：键是标签名（动态，多少个都行），值是颜色或颜色加一句说明。
 * 颜色值本身的合法性（六位十六进制）由配色核定，这里只管形状：
 * 非法颜色按「还没配颜色」由调用方归一，不算文件坏掉（沿房间既有口径）。
 * 自包含：小工具自己写一遍，不引用别的单元（产物零相对引用，见 workspace.ts 头注）。
 * 文本入口（parseLabelsText）也住这里：房间文件不许用裸包引用（跨房门禁），
 * 而产物在 shared 层用裸包是允许的方向；入口守卫的数字与适配器同值，
 * 两处行为一致由门禁钉（超大与别名各有一条走房间路径的用例）。
 */

import { parse as parseYaml } from 'yaml'
import type { ConfigParseResult, ConfigStringifyResult } from './ports.js'

/** 文件字符数上限（与适配器同数；超了说明拿错了文件）。 */
export const MAX_LABELS_FILE_CHARS = 65536
/** 别名数量上限（与适配器同数；正常文件里一个别名都不会有）。 */
export const MAX_LABELS_ALIASES = 50

/** 标签配色数据的新路径（YAML）与老路径（JSON，只做兼容读）。 */
export const LABEL_COLORS_YAML_REL = 'docs/agents/label-colors.yaml'
export const LABEL_COLORS_JSON_REL = 'docs/agents/label-colors.json'
/** 核认识的版本就是 1（老文件没有版本，当 1 读）。 */
export const LABEL_COLORS_KNOWN_VERSION = 1

const HEADER = ['# Comments in this file are generated by the plugin; your own comments will be replaced on the next write.']
const COMMENT_VERSION = '# Data version (a newer version unknown to the core is read-only)'
const ENTRY_KEYS = ['color', 'description']

function isRecord(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v)
}

function isInt(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v)
}

/** 不能当标签名的名字：会撞上原型链，读出来就变味。 */
function isDangerousKey(key: string): boolean {
  return key === '__proto__' || key === 'constructor' || key === 'prototype'
}

function fail(reason: 'bad-shape' | 'unknown-keys', message: string, keys?: string[]): ConfigParseResult {
  return keys ? { ok: false, reason, message, keys } : { ok: false, reason, message }
}

/** 写 YAML 纯量：能裸写才裸写，拿不准的一律双引号（标签名与颜色共用这一支）。 */
function esc(text: string): string {
  if (text === '') return "''"
  const lower = text.toLowerCase()
  if (/^[A-Za-z_][A-Za-z0-9_\-]*$/.test(text) && lower !== 'yes' && lower !== 'no' && lower !== 'y' && lower !== 'n' && lower !== 'on' && lower !== 'off' && lower !== 'true' && lower !== 'false' && lower !== 'null' && lower !== '~') {
    return text
  }
  return (
    '"' +
    text
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
      .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, (c) => '\\u' + ('0000' + c.charCodeAt(0).toString(16)).slice(-4)) +
    '"'
  )
}

/** 数一数文本里用了多少个别名。注释里的不算，先去掉行注释。 */
function countAliases(text: string): number {
  const noComments = text.replace(/(^|\s)#[^\n]*$/gm, '$1')
  const hits = noComments.match(/(^|[\s\[{,])\*[A-Za-z0-9_-]+/g)
  return hits ? hits.length : 0
}

/**
 * 文本入口：超大与别名两道守卫 → YAML 解析（钉死 core 模式）→ 校验。
 * 给不能用裸包引用的调用方（后端房间）；宿主适配器走自己的 parseConfig，
 * 两处守卫数字相同、行为一致（门禁从行为上钉住）。
 */
export function parseLabelsText(text: unknown): ConfigParseResult {
  if (typeof text !== 'string') {
    return { ok: false, reason: 'yaml-error', message: 'the input to parse is not text' }
  }
  const stripped = text.replace(/^\uFEFF/, '')
  if (stripped.length > MAX_LABELS_FILE_CHARS) {
    return {
      ok: false,
      reason: 'oversize',
      message: 'this file is too large (' + stripped.length + ' characters, limit ' + MAX_LABELS_FILE_CHARS + ' characters); the core refuses to parse it: config files should be small, and this suggests the wrong file',
    }
  }
  if (countAliases(stripped) > MAX_LABELS_ALIASES) {
    return {
      ok: false,
      reason: 'aliases',
      message: 'this file has too many aliases (limit ' + MAX_LABELS_ALIASES + '); the core refuses to parse it: a normal config file has no aliases',
    }
  }
  let doc: unknown = null
  try {
    doc = parseYaml(stripped, { schema: 'core', maxAliasCount: MAX_LABELS_ALIASES, uniqueKeys: true })
  } catch (e) {
    const msg = String((e && (e as Error).message) || e || '')
    if (/alias/i.test(msg)) {
      return { ok: false, reason: 'aliases', message: 'this file has too many aliases; the core refuses to parse it: a normal config file has no aliases' }
    }
    return { ok: false, reason: 'yaml-error', message: 'this file is not valid YAML (nor legacy JSON): ' + msg.slice(0, 160) }
  }
  if (doc === undefined || doc === null || (typeof doc === 'string' && (doc as string).trim() === '')) {
    return { ok: false, reason: 'bad-shape', message: 'this file is empty (only whitespace)' }
  }
  return parseLabelColors(doc)
}

/** 校验一份已解析出来的标签配色。版本高于认识时读成功标只读。 */
export function parseLabelColors(doc: unknown): ConfigParseResult {
  if (!isRecord(doc)) return fail('bad-shape', 'the label colors file must be a label-to-color mapping, not a list or text')
  let version = 1
  if (doc['version'] !== undefined) {
    // 兼容注意：版本号的位置就叫 version，所以标签名不能叫 version。
    // 老文件里如果真有一个叫 version 的标签，这里会明确报错并指改名，不断言它是版本。
    if (!isInt(doc['version'])) return fail('bad-shape', 'version in the label colors file must be numeric (if version is a label name, rename it: this field is reserved for the version number)')
    version = doc['version'] as number
    if (version > LABEL_COLORS_KNOWN_VERSION) {
      return {
        ok: true,
        value: doc,
        readonly: true,
        warnings: ['version-newer: this file has version ' + version + ', but the core only understands version 1; it may be displayed but must not be written back. Upgrade the plugin.'],
      }
    }
    if (version < 1) return fail('bad-shape', 'version in the label colors file must be 1 (legacy files without a version still load)')
  }
  const colors: Record<string, unknown> = {}
  for (const name of Object.keys(doc)) {
    if (name === 'version') continue
    if (name.trim() === '') return fail('bad-shape', 'the label colors file has an empty label name')
    if (isDangerousKey(name)) return fail('bad-shape', 'this label name is not allowed in the label colors file: ' + name)
    const entry = doc[name]
    if (typeof entry === 'string') {
      colors[name] = entry
      continue
    }
    if (isRecord(entry)) {
      const strange = Object.keys(entry).filter((k) => ENTRY_KEYS.indexOf(k) < 0)
      if (strange.length > 0) {
        return fail('unknown-keys', 'label "' + name + '" has unknown fields in the label colors file: ' + strange.join(', '), strange)
      }
      if (typeof entry['color'] !== 'string') {
        return fail('bad-shape', 'label "' + name + '" must have a string color (six hex digits without #)')
      }
      if (entry['description'] !== undefined && typeof entry['description'] !== 'string') {
        return fail('bad-shape', 'label "' + name + '" must have a string description')
      }
      const norm: Record<string, unknown> = { color: entry['color'] }
      if (entry['description'] !== undefined) norm['description'] = entry['description']
      colors[name] = norm
      continue
    }
    return fail(
      'bad-shape',
      'label "' + name + '" has an invalid color value; use either a color string such as "8b5cf6" or {"color": "8b5cf6", "description": "map ticket"}',
    )
  }
  return { ok: true, value: { version, colors }, readonly: false, warnings: [] }
}

/**
 * 拼装。收两种形状：直给标签表，或 {version, colors} 包裹（读回来的就是后者），
 * 写出来永远是完整模板（version 在头，标签按给进来的顺序）。
 */
export function stringifyLabelColors(value: unknown): ConfigStringifyResult {
  if (!isRecord(value)) return { ok: false, reason: 'bad-shape', message: 'label colors to write must be a label-to-color mapping' }
  // 包裹与直给二选一：带 colors 键的就是 {version, colors} 包裹；直给的标签表里
  // 不能出现 version / colors 这两个名字（它们是格式保留字，标签请改名）。
  const looksWrapped = value['colors'] !== undefined || isInt(value['version'])
  let version = 1
  let table: unknown = value
  if (looksWrapped) {
    if (!isInt(value['version'])) return { ok: false, reason: 'bad-shape', message: 'version in the label colors to write must be the number 1' }
    version = value['version'] as number
    table = value['colors']
  } else if ('version' in value || 'colors' in value) {
    return { ok: false, reason: 'bad-shape', message: 'a bare label table cannot contain version or colors (reserved format fields). Wrap it in {version, colors}, or rename those labels.' }
  }
  if (version > LABEL_COLORS_KNOWN_VERSION) {
    return {
      ok: false,
      reason: 'version-newer',
      message: 'write refused: these label colors have version ' + version + ', but the core only understands version 1. Writing with an older version would erase new fields; upgrade the plugin before editing.',
    }
  }
  if (version !== LABEL_COLORS_KNOWN_VERSION) return { ok: false, reason: 'bad-shape', message: 'version in the label colors to write must be 1' }
  if (!isRecord(table)) return { ok: false, reason: 'bad-shape', message: 'colors in the label colors to write must be a label-to-color mapping' }
  const probe: Record<string, unknown> = { version }
  for (const k of Object.keys(table)) probe[k] = (table as Record<string, unknown>)[k]
  const check = parseLabelColors(probe)
  if (!check.ok) return { ok: false, reason: check.reason === 'unknown-keys' ? 'unknown-keys' : 'bad-shape', message: check.message, keys: check.keys }
  const colors = ((check as { ok: true; value: Record<string, unknown> }).value['colors'] || {}) as Record<string, unknown>
  const lines = [...HEADER]
  lines.push(COMMENT_VERSION)
  lines.push('version: 1')
  for (const name of Object.keys(colors)) {
    const entry = colors[name]
    if (typeof entry === 'string') {
      lines.push(esc(name) + ': ' + esc(entry))
    } else {
      const rec = entry as Record<string, unknown>
      const inner =
        '{"color": ' + esc(String(rec['color'])) +
        (rec['description'] === undefined ? '' : ', "description": ' + esc(String(rec['description']))) +
        '}'
      lines.push(esc(name) + ': ' + inner)
    }
  }
  return { ok: true, text: lines.join('\n') + '\n' }
}
