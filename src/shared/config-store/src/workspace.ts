import { parse as parseYaml } from 'yaml'
import type { ConfigParseResult, ConfigStringifyResult } from './ports.js'

/** 工作区后端配置的新路径（YAML）与老路径（JSON，只做兼容读）。 */
export const WORKSPACE_YAML_REL = 'docs/agents/workspace.yaml'
export const WORKSPACE_JSON_REL = 'docs/agents/workspace.json'
/**
 * 人写的说明文件路径（后端选择说明）。判定层从不读它、也不拿它当根标记；
 * 它回答的是「这个工作区用哪个后端」，与「这一层是不是工作区」是两件事。
 * 面板的「工作区已初始化」检查仍然看它在不在（初始化流程会写下这份说明）。
 */
export const WORKSPACE_TRACKER_DOC_REL = 'docs/agents/issue-tracker.md'
/** 核认识的版本就是 2（老 JSON 是版本 1，读进来做迁移）。 */
export const WORKSPACE_KNOWN_VERSION = 2

/** 文件字符数上限（与适配器同数；超了说明拿错了文件）。 */
export const MAX_WORKSPACE_FILE_CHARS = 65536
/** 别名数量上限（与适配器同数；正常文件里一个别名都不会有）。 */
export const MAX_WORKSPACE_ALIASES = 50

const HEADER = [
  '# Comments in this file are generated by the plugin; your own comments will be replaced on the next write.',
  '# This file travels with the repository: once committed it is shared with the team, and changes affect everyone.',
]
const COMMENT_BACKEND = '# Backend used by this workspace'
const COMMENT_PICKED = '# When this selection was made (milliseconds)'
const COMMENT_SOURCE =
  '# Who made this selection: user=selected by a person in the panel; migrated=imported from legacy local memory; detected=generated from a declaration file or automatic detection'
const COMMENT_LAYOUT_1 = '# Domain document layout: single=one context (shared terminology, one GLOSSARY.md at the root);'
const COMMENT_LAYOUT_2 = '# multi=multiple contexts (separate terminology, a GLOSSARY.md per subproject, linked from the root GLOSSARY-MAP.md)'

const SOURCES_V2 = ['user', 'migrated', 'detected']
const SOURCES_V1 = ['user', 'migrated', 'detected', 'auto']
const KNOWN_KEYS = ['version', 'backendId', 'pickedAt', 'source', 'layout']

function isRecord(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v)
}

function isInt(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v)
}

function fail(reason: 'bad-shape' | 'unknown-keys', message: string, keys?: string[]): ConfigParseResult {
  return keys ? { ok: false, reason, message, keys } : { ok: false, reason, message }
}

/** 写 YAML 纯量：能裸写才裸写，拿不准的一律双引号，只写不错的保守方向。 */
function esc(text: string): string {
  if (text === '') return "''"
  const lower = text.toLowerCase()
  if (/^[A-Za-z_][A-Za-z0-9_\-]*$/.test(text) && lower !== 'yes' && lower !== 'no' && lower !== 'y' && lower !== 'n' && lower !== 'on' && lower !== 'off' && lower !== 'true' && lower !== 'false' && lower !== 'null' && lower !== '~') {
    return text
  }
  return (
    '"' +
    text
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
      .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, (c) => '\\u' + ('0000' + c.charCodeAt(0).toString(16)).slice(-4)) +
    '"'
  )
}

/** 数一数文本里用了多少个别名。注释里的不算，先去掉行注释。 */
function countAliases(text: string): number {
  const noComments = text.replace(/(^|\s)#[^\n]*$/gm, '$1')
  const hits = noComments.match(/(^|[\s\[{,])\*[A-Za-z0-9_-]+/g)
  return hits ? hits.length : 0
}

/**
 * 文本入口：超大与别名两道守卫 → YAML 解析（钉死 core 模式）→ 校验。
 * 给不能用裸包引用的调用方（兼容垫片）；宿主适配器走自己的 parseConfig，
 * 两处守卫数字相同、行为一致（门禁从行为上钉住）。
 * layouts 是这次允许的布局取值（调用方从唯一真源 src/shared/doc-layout 取，见文件头）。
 */
export function parseWorkspaceText(text: unknown, layouts: readonly string[]): ConfigParseResult {
  if (typeof text !== 'string') {
    return { ok: false, reason: 'yaml-error', message: 'the input to parse is not text' }
  }
  const stripped = text.replace(/^\uFEFF/, '')
  if (stripped.length > MAX_WORKSPACE_FILE_CHARS) {
    return {
      ok: false,
      reason: 'oversize',
      message: 'this file is too large (' + stripped.length + ' characters, limit ' + MAX_WORKSPACE_FILE_CHARS + ' characters); the core refuses to parse it: config files should be small, and this suggests the wrong file',
    }
  }
  if (countAliases(stripped) > MAX_WORKSPACE_ALIASES) {
    return {
      ok: false,
      reason: 'aliases',
      message: 'this file has too many aliases (limit ' + MAX_WORKSPACE_ALIASES + '); the core refuses to parse it: a normal config file has no aliases',
    }
  }
  let doc: unknown = null
  try {
    doc = parseYaml(stripped, { schema: 'core', maxAliasCount: MAX_WORKSPACE_ALIASES, uniqueKeys: true })
  } catch (e) {
    const msg = String((e && (e as Error).message) || e || '')
    if (/alias/i.test(msg)) {
      return { ok: false, reason: 'aliases', message: 'this file has too many aliases; the core refuses to parse it: a normal config file has no aliases' }
    }
    return { ok: false, reason: 'yaml-error', message: 'this file is not valid YAML (nor legacy JSON): ' + msg.slice(0, 160) }
  }
  if (doc === undefined || doc === null || (typeof doc === 'string' && (doc as string).trim() === '')) {
    return { ok: false, reason: 'bad-shape', message: 'this file is empty (only whitespace)' }
  }
  return parseWorkspace(doc, layouts)
}

/** 校验一份已解析出来的工作区配置。版本高于认识时读成功标只读（写时由拼装拒绝）。
 *  layouts 是这次允许的布局取值（调用方从唯一真源 src/shared/doc-layout 取，见文件头）。 */
export function parseWorkspace(doc: unknown, layouts: readonly string[]): ConfigParseResult {
  if (!isRecord(doc)) return fail('bad-shape', 'the workspace config must be a name-to-value mapping, not a list or text')
  const strange = Object.keys(doc).filter((k) => KNOWN_KEYS.indexOf(k) < 0)
  if (strange.length > 0) {
    return fail('unknown-keys', 'the workspace config has fields unknown to the core: ' + strange.join(', '), strange)
  }
  if (!isInt(doc['version'])) return fail('bad-shape', 'version in the workspace config must be numeric')
  const version = doc['version'] as number
  if (version > WORKSPACE_KNOWN_VERSION) {
    return {
      ok: true,
      value: doc,
      readonly: true,
      warnings: ['version-newer: this file has version ' + version + ', but the core only understands version 2; it may be displayed but must not be written back (that would erase new fields). Upgrade the plugin.'],
    }
  }
  if (version !== 1 && version !== 2) return fail('bad-shape', 'version in the workspace config must be 1 (legacy JSON migration) or 2')
  if (typeof doc['backendId'] !== 'string' || doc['backendId'].trim() === '') {
    return fail('bad-shape', 'backendId in the workspace config must be a nonempty string (YAML reads unquoted yes/no/on as text and 1.10 as a number; type mismatches are rejected as malformed)')
  }
  if (!isInt(doc['pickedAt']) || (doc['pickedAt'] as number) < 0) {
    return fail('bad-shape', 'pickedAt in the workspace config must be the selection time (milliseconds, a nonnegative integer)')
  }
  const allowed = version === 2 ? SOURCES_V2 : SOURCES_V1
  if (typeof doc['source'] !== 'string' || allowed.indexOf(doc['source']) < 0) {
    return fail(
      'bad-shape',
      version === 2
        ? 'source in the workspace config must be user (selected by a person), migrated (imported from legacy memory), or detected (from a declaration or automatic detection)'
        : 'source in the workspace config must be user, migrated, detected, or auto',
    )
  }
  // 布局缺席允许：v1 老文件本来就没有；v2 文件缺了也照读（值里不带 layout 键）。
  // 写布局是调用方的事（有点确认/迁移时带上）；一旦写进去，覆盖写必须读改写保住。
  if (doc['layout'] !== undefined && (typeof doc['layout'] !== 'string' || layouts.indexOf(doc['layout']) < 0)) {
    return fail('bad-shape', 'layout in the workspace config must be one of: ' + layouts.join(', '))
  }
  const value: Record<string, unknown> = {
    version,
    backendId: (doc['backendId'] as string).trim(),
    pickedAt: doc['pickedAt'],
    source: doc['source'],
  }
  if (doc['layout'] !== undefined) value['layout'] = doc['layout']
  return { ok: true, value, readonly: false, warnings: [] }
}

/** 拼装：模板 + 值，一律出版本 2；高版本拒绝写（旧版本不许把新字段抹掉）。
 *  version 缺席默认 2，传 1 视为升级写出（老版本 1 只用来读）；布局缺席整段省略。
 *  layouts 是这次允许的布局取值（调用方从唯一真源 src/shared/doc-layout 取，见文件头）。 */
export function stringifyWorkspace(value: unknown, layouts: readonly string[]): ConfigStringifyResult {
  if (!isRecord(value)) return { ok: false, reason: 'bad-shape', message: 'the workspace config to write must be a name-to-value mapping' }
  const strange = Object.keys(value).filter((k) => KNOWN_KEYS.indexOf(k) < 0)
  if (strange.length > 0) {
    return { ok: false, reason: 'unknown-keys', message: 'the workspace config to write has unknown fields that the core will not write: ' + strange.join(', '), keys: strange }
  }
  const version = value['version'] === undefined ? WORKSPACE_KNOWN_VERSION : value['version']
  if (!isInt(version)) return { ok: false, reason: 'bad-shape', message: 'version in the workspace config to write must be numeric (defaults to 2 when absent)' }
  if ((version as number) > WORKSPACE_KNOWN_VERSION) {
    return {
      ok: false,
      reason: 'version-newer',
      message: 'write refused: this workspace config has version ' + String(version) + ', but the core only understands version 2. Writing with an older version would erase new fields; upgrade the plugin before editing.',
    }
  }
  if (version !== 1 && version !== WORKSPACE_KNOWN_VERSION) return { ok: false, reason: 'bad-shape', message: 'version in the workspace config to write must be 1 (upgraded on write) or 2' }
  const check = parseWorkspace({
    version: WORKSPACE_KNOWN_VERSION,
    backendId: value['backendId'],
    pickedAt: value['pickedAt'],
    source: value['source'],
    layout: value['layout'],
  }, layouts)
  if (!check.ok) return { ok: false, reason: check.reason === 'unknown-keys' ? 'unknown-keys' : 'bad-shape', message: check.message, keys: check.keys }
  const v = (check as { ok: true; value: Record<string, unknown> }).value
  const lines = [...HEADER]
  lines.push('version: ' + String(v['version']))
  lines.push(COMMENT_BACKEND)
  lines.push('backendId: ' + esc(String(v['backendId'])))
  lines.push(COMMENT_PICKED)
  lines.push('pickedAt: ' + String(v['pickedAt']))
  lines.push(COMMENT_SOURCE)
  lines.push('source: ' + esc(String(v['source'])))
  if (v['layout'] !== undefined) {
    lines.push(COMMENT_LAYOUT_1)
    lines.push(COMMENT_LAYOUT_2)
    lines.push('layout: ' + esc(String(v['layout'])))
  }
  return { ok: true, text: lines.join('\n') + '\n' }
}
