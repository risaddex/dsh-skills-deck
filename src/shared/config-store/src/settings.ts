/**
 * src/shared/config-store/src/settings.ts —— 本机全局设置的校验与拼装（#1012）
 *
 * 纯函数，不碰文件系统。文件：`<用户主目录>/.dsh/mattskillsdeck/settings.yaml`（版本 1）。
 * 注释原文与 #1012 票定案骨架逐字一致。读时缺节给默认（写回去自然补全），
 * 未知名字一律拒绝（静默丢掉用户手写的键等于丢数据）。
 * 自包含：小工具自己写一遍，不引用别的单元（产物零相对引用，见 workspace.ts 头注）。
 * YAML 入口守卫住宿主适配器的 parseConfig（唯一入口）。
 *
 * 每个工作区那一条记录里的三个开关（#1612 维护者拍板；#1879 加第三个）：
 *   · statusBar（胶囊状态栏）只认 show 显示、hide 收起（缺省收起）。收起时状态栏只剩一条折叠条，
 *     环境检查类横幅也一起不显示。
 *   · deckTools（deck 工具箱）只认 on 打开、off 关闭（缺省打开）。关掉时该工作区的模型工具、
 *     胶囊状态栏、右侧面板三处一起关。
 *   · suggest（下一步建议气泡）只认 on 显示、off 不显示（缺省显示）。关掉只让气泡不出现，
 *     模型照常可以调 suggest_next_steps；这一格与上面两格一样按工作区记。
 * 旧字段 bannerFolded 只保留最少的一步读兼容（#1612 维护者 2026-10-29 拍板删掉旧 localStorage 迁移之后）：
 *   接受这个键（否则旧文件整份会被判成多出来的名字），只把「展开」那一种旧值换算成 statusBar: show；
 *   旧版把「收起」记作 true（也是缺省），那种情况按新缺省 hide，不需要换算。写出去的一份里不再出现它。
 *
 * 每个工作区那一条记录上还有一个临时标记 unopened（#1641）：设置页的工作区名单里有些工作区还没打开过，
 *   认不出它的工作区根，只能先按名单上的路径记一条。这条记录带 unopened: true，表示它还没有归到工作区根
 *   那一条，等工作区打开、认出根以后会合并过去。它只是一个说明，不是开关，缺了与 false 同义。
 *   带这个标记的记录是「临时记录」（#1640）：只写用户真点过的那几格开关，缺的格不补缺省 ——「格在不在」
 *   就是「用户点过没点过」，认出工作区根以后靠这一点决定合并时搬哪几格；普通记录（已经归到根的那一条）
 *   照旧几格齐全。
 */

import type { ConfigParseResult, ConfigStringifyResult } from './ports.js'

/** 本机全局设置：核认识的版本就是 1。 */
export const SETTINGS_KNOWN_VERSION = 1

/** 本机设置在用户主目录下的相对位置（调用方拼绝对路径，核里不碰主目录）。 */
export const SETTINGS_REL_SEGMENTS = ['.dsh', 'mattskillsdeck', 'settings.yaml']

/**
 * 设置发布槽位的名字（#1612）：实例宿主在每次成功读 / 写本机设置之后，把归一后的设置文档投到
 * globalThis 上这个槽位，宿主侧的 deck 工具闸门订阅它。名字只在这里定义一次，
 * src/host/settingsPhones.ts（发布方）与 src/host/deckToolGate.ts（订阅方）都从这里导入。
 * 放在核里而不是某一边，是因为它是「本机设置」这件事的共享契约：谁都不该独占一份字符串副本。
 */
export const DECK_SETTINGS_BUS_SLOT = '__dsh_mattskillsdeck_settings_bus__'

const HEADER = ['# Comments in this file are generated by the plugin; your own comments will be replaced on the next write.']
const COMMENT_UI = '# Interface preferences (defaults for all workspaces on this machine)'
const COMMENT_STATE = '# Main list state filter and sort order'
const COMMENT_WORKSPACES = '# Per-workspace view state (key = workspace root directory)'
const COMMENT_STATUS_BAR = '# Capsule status bar: show or hide (hidden leaves only a collapsed bar)'
const COMMENT_DECK_TOOLS = '# Deck toolbox: on or off (off disables model tools, capsule status bar and right panel together)'
const COMMENT_SUGGEST = '# Next-step suggestion bubbles: on or off (off hides only bubbles; the model may still suggest steps)'
const COMMENT_NOREPO = '# Whether the no-repository red card has been dismissed'
const COMMENT_SUBWS = '# Whether the red folder marker explanation has already opened automatically'
const COMMENT_UNOPENED = '# This entry temporarily uses the settings workspace-list path (the workspace has not been opened); once opened and its root recognized, it merges into the root entry'
const COMMENT_DEBUG = '# Local diagnostic logging switch'
const COMMENT_TEMPLATES = '# Action templates (empty = default text)'

const TOP_KEYS = ['version', 'ui', 'workspaces', 'debug', 'templates']
// labelClicks 只在「读」这一侧认得（老文件里可能已经写进去了，读出来不能报错），写出去的一份里没有它：
// 维护者 2026-10-12 拍板这项不落盘——它只是标签 chip 排序用的热度，丢了不影响功能，没必要占文件。
const UI_KEYS = ['stateFilter', 'sortKey', 'sortDir', 'labelClicks']
// workspaces 每条记录认的名字：三个开关（statusBar、deckTools、suggest）、两个旧布尔开关（noRepoDismissed、
// subwsMarkAutoShown），旧字段 bannerFolded（只为让旧文件读得进来；只换算「展开」那一种旧值，见 parseSettings），
// 以及 #1641 的临时标记 unopened（这条记录先按设置页工作区名单上的路径记着，还没归到工作区根那一条）。
const WS_KEYS = ['statusBar', 'deckTools', 'suggest', 'bannerFolded', 'noRepoDismissed', 'subwsMarkAutoShown', 'unopened']
// 三个文字开关各自允许的字面量：值必须逐字是其中之一，别的一律按坏形状回。
const WS_STATUS_BAR_VALUES = ['show', 'hide']
const WS_DECK_TOOLS_VALUES = ['on', 'off']
const WS_SUGGEST_VALUES = ['on', 'off']
const DEBUG_KEYS = ['enabled', 'sampleRate']

function isRecord(v: unknown): v is Record<string, unknown> {
  return !!v && typeof v === 'object' && !Array.isArray(v)
}

function isFiniteNumber(v: unknown): v is number {
  return typeof v === 'number' && Number.isFinite(v)
}

function isInt(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v)
}

/** 不能当数据键的名字：会撞上原型链，读出来就变味。 */
function isDangerousKey(key: string): boolean {
  return key === '__proto__' || key === 'constructor' || key === 'prototype'
}

function fail(reason: 'bad-shape' | 'unknown-keys', message: string, keys?: string[]): ConfigParseResult {
  return keys ? { ok: false, reason, message, keys } : { ok: false, reason, message }
}

/** 写 YAML 纯量：能裸写才裸写，拿不准的一律双引号（键与值共用这一支）。 */
function esc(text: string): string {
  if (text === '') return "''"
  const lower = text.toLowerCase()
  if (/^[A-Za-z_][A-Za-z0-9_\-]*$/.test(text) && lower !== 'yes' && lower !== 'no' && lower !== 'y' && lower !== 'n' && lower !== 'on' && lower !== 'off' && lower !== 'true' && lower !== 'false' && lower !== 'null' && lower !== '~') {
    return text
  }
  return (
    '"' +
    text
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
      .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, (c) => '\\u' + ('0000' + c.charCodeAt(0).toString(16)).slice(-4)) +
    '"'
  )
}

function unknownIn(obj: Record<string, unknown>, allowed: string[]): string[] {
  return Object.keys(obj).filter((k) => allowed.indexOf(k) < 0)
}

/** 校验一份已解析出来的本机设置。版本高于认识时读成功标只读。 */
export function parseSettings(doc: unknown): ConfigParseResult {
  if (!isRecord(doc)) return fail('bad-shape', 'the local settings file must be a name-to-value mapping, not a list or text')
  const strange = unknownIn(doc, TOP_KEYS)
  if (strange.length > 0) {
    return fail('unknown-keys', 'the local settings file has fields unknown to the core: ' + strange.join(', '), strange)
  }
  if (!isInt(doc['version'])) return fail('bad-shape', 'version in the local settings file must be numeric')
  const version = doc['version'] as number
  if (version > SETTINGS_KNOWN_VERSION) {
    return {
      ok: true,
      value: doc,
      readonly: true,
      warnings: ['version-newer: this file has version ' + version + ', but the core only understands version 1; it may be displayed but must not be written back. Upgrade the plugin.'],
    }
  }
  if (version !== SETTINGS_KNOWN_VERSION) return fail('bad-shape', 'version in the local settings file must be 1')

  const uiRaw = doc['ui'] === undefined ? {} : doc['ui']
  if (!isRecord(uiRaw)) return fail('bad-shape', 'ui in the local settings file must be a name-to-value mapping')
  const uiStrange = unknownIn(uiRaw, UI_KEYS)
  if (uiStrange.length > 0) return fail('unknown-keys', 'the local settings ui section has unknown fields: ' + uiStrange.join(', '), uiStrange)
  for (const k of ['stateFilter', 'sortKey', 'sortDir']) {
    if (uiRaw[k] !== undefined && typeof uiRaw[k] !== 'string') {
      return fail('bad-shape', 'in the local settings ui section, ' + k + ' must be a string')
    }
  }
  const clicksRaw = uiRaw['labelClicks'] === undefined ? {} : uiRaw['labelClicks']
  if (!isRecord(clicksRaw)) return fail('bad-shape', 'labelClicks in the local settings ui section must map labels to counts')
  const clicks: Record<string, unknown> = {}
  for (const name of Object.keys(clicksRaw)) {
    if (isDangerousKey(name)) return fail('bad-shape', 'this name is not allowed in local settings labelClicks: ' + name)
    const n = clicksRaw[name]
    if (!isFiniteNumber(n) || (n as number) < 0) {
      return fail('bad-shape', 'in local settings labelClicks, "' + name + '" must have a nonnegative numeric count')
    }
    clicks[name] = n
  }

  // workspaces 节：键是工作区根的可读路径（动态），值里认五个开关（胶囊状态栏缺了默认收起、deck 工具箱缺了默认开、
  // 下一步建议气泡缺了默认显示，其余两个旧开关缺了默认关），还可以带一个临时标记 unopened（见文件头；只记录 true，缺了与 false 同义）。
  // 带标记的临时记录只留写下来的格（#1640），普通记录才把这几个开关的缺省补齐。
  // 旧字段 bannerFolded 只把「展开」（false）换算成 statusBar: show，归一结果里不带它。
  const wsRaw = doc['workspaces'] === undefined ? {} : doc['workspaces']
  if (!isRecord(wsRaw)) return fail('bad-shape', 'workspaces in the local settings file must map workspace roots to switches')
  const workspaces: Record<string, unknown> = {}
  for (const root of Object.keys(wsRaw)) {
    if (root.trim() === '') return fail('bad-shape', 'the local settings workspaces section has an empty key (keys must be workspace root directories)')
    if (isDangerousKey(root)) return fail('bad-shape', 'this name is not allowed in the local settings workspaces section: ' + root)
    const entry = wsRaw[root]
    if (!isRecord(entry)) return fail('bad-shape', 'in the local settings workspaces section, "' + root + '" must be a set of switches')
    const entryStrange = unknownIn(entry, WS_KEYS)
    if (entryStrange.length > 0) {
      return fail('unknown-keys', 'in the local settings workspaces section, "' + root + '" has unknown fields: ' + entryStrange.join(', '), entryStrange)
    }
    // 先认临时标记 unopened：它决定这一条是普通记录（缺格补默认）还是临时记录（只留写下来的格）。
    //   值不是真假值一律按坏形状回，免得用户手写的 unopened: yes 被 YAML 读成文字后悄悄当成没写。
    if (entry['unopened'] !== undefined && typeof entry['unopened'] !== 'boolean') {
      return fail('bad-shape', 'in the local settings workspaces section, "' + root + '" must have unopened set to true or omitted (true means the entry still uses the workspace-list path because the workspace has not been opened)')
    }
    const isTemp: boolean = entry['unopened'] === true
    // 普通记录缺格补默认；临时记录一格都不补 —— 写下来的才是用户点过的（#1640 合并时按这个判，见文件头）。
    const norm: Record<string, unknown> = isTemp
      ? { unopened: true }
      : { statusBar: 'hide', deckTools: 'on', suggest: 'on', noRepoDismissed: false, subwsMarkAutoShown: false }
    // bannerFolded 是已发布过的旧字段：接受它（旧文件里可能有，否则整份会被判 unknown-keys）。
    // 只保留「展开」这一种旧值的换算（false → statusBar: show）—— 验收 ⑦ 要求升级前手动展开过的工作区，
    // 升级后胶囊仍显示着；旧版把「收起」记作 true（也是缺省），那种情况按新缺省 hide，不需要换算。
    // 旧 localStorage 键（dsws.bannerFold）那套迁移已按维护者 2026-10-29 的要求整段删除，这里只剩这一行读兼容。
    if (entry['bannerFolded'] === false) norm['statusBar'] = 'show'
    // statusBar 显式写着时以它为准。
    if (entry['statusBar'] !== undefined) {
      const okBar: boolean = typeof entry['statusBar'] === 'string' && WS_STATUS_BAR_VALUES.indexOf(entry['statusBar'] as string) >= 0
      if (!okBar) {
        return fail('bad-shape', 'in the local settings workspaces section, "' + root + '" must have statusBar set to show or hide (the capsule status bar), received: ' + String(entry['statusBar']))
      }
      norm['statusBar'] = entry['statusBar']
    }
    if (entry['deckTools'] !== undefined) {
      const okTools: boolean = typeof entry['deckTools'] === 'string' && WS_DECK_TOOLS_VALUES.indexOf(entry['deckTools'] as string) >= 0
      if (!okTools) {
        return fail('bad-shape', 'in the local settings workspaces section, "' + root + '" must have deckTools set to on or off (the deck toolbox), received: ' + String(entry['deckTools']))
      }
      norm['deckTools'] = entry['deckTools']
    }
    // #1879：下一步建议气泡的开关，缺了按显示（今天「deck 开着就显示」的行为）。
    if (entry['suggest'] !== undefined) {
      const okSuggest: boolean = typeof entry['suggest'] === 'string' && WS_SUGGEST_VALUES.indexOf(entry['suggest'] as string) >= 0
      if (!okSuggest) {
        return fail('bad-shape', 'in the local settings workspaces section, "' + root + '" must have suggest set to on or off (next-step suggestion bubbles), received: ' + String(entry['suggest']))
      }
      norm['suggest'] = entry['suggest']
    }
    // 两个旧布尔开关照旧：值必须是真假值，缺了用默认。
    for (const k of ['noRepoDismissed', 'subwsMarkAutoShown']) {
      if (entry[k] === undefined) continue
      if (typeof entry[k] !== 'boolean') {
        return fail('bad-shape', 'in the local settings workspaces section, "' + root + '", field ' + k + ' must be a boolean (YAML reads unquoted yes/no/on as text, which is rejected as malformed)')
      }
      norm[k] = entry[k]
    }
    workspaces[root] = norm
  }

  const debugRaw = doc['debug'] === undefined ? {} : doc['debug']
  if (!isRecord(debugRaw)) return fail('bad-shape', 'debug in the local settings file must be a name-to-value mapping')
  const debugStrange = unknownIn(debugRaw, DEBUG_KEYS)
  if (debugStrange.length > 0) return fail('unknown-keys', 'the local settings debug section has unknown fields: ' + debugStrange.join(', '), debugStrange)
  const enabled = debugRaw['enabled'] === undefined ? false : debugRaw['enabled']
  if (typeof enabled !== 'boolean') return fail('bad-shape', 'enabled in the local settings debug section must be a boolean')
  const sampleRate = debugRaw['sampleRate'] === undefined ? 1 : debugRaw['sampleRate']
  if (!isFiniteNumber(sampleRate) || (sampleRate as number) < 0 || (sampleRate as number) > 1) {
    return fail('bad-shape', 'sampleRate in the local settings debug section must be a number from 0 to 1')
  }

  const tplRaw = doc['templates'] === undefined ? {} : doc['templates']
  if (!isRecord(tplRaw)) return fail('bad-shape', 'templates in the local settings file must map actions to text')
  const templates: Record<string, unknown> = {}
  for (const name of Object.keys(tplRaw)) {
    if (isDangerousKey(name)) return fail('bad-shape', 'this name is not allowed in local settings templates: ' + name)
    if (typeof tplRaw[name] !== 'string') return fail('bad-shape', 'in local settings templates, "' + name + '" must have a string value')
    templates[name] = tplRaw[name]
  }

  return {
    ok: true,
    value: {
      version: 1,
      ui: {
        stateFilter: uiRaw['stateFilter'] === undefined ? '' : uiRaw['stateFilter'],
        sortKey: uiRaw['sortKey'] === undefined ? '' : uiRaw['sortKey'],
        sortDir: uiRaw['sortDir'] === undefined ? '' : uiRaw['sortDir'],
        labelClicks: clicks,
      },
      workspaces,
      debug: { enabled, sampleRate },
      templates,
    },
    readonly: false,
    warnings: [],
  }
}

/** 拼装：先按读的同一套规矩校验并补默认，写出来的永远是完整模板。 */
export function stringifySettings(value: unknown): ConfigStringifyResult {
  if (!isRecord(value)) return { ok: false, reason: 'bad-shape', message: 'local settings to write must be a name-to-value mapping' }
  const strange = unknownIn(value, TOP_KEYS)
  if (strange.length > 0) {
    return { ok: false, reason: 'unknown-keys', message: 'the local settings to write contain unknown fields that the core will not write: ' + strange.join(', '), keys: strange }
  }
  if (!isInt(value['version'])) return { ok: false, reason: 'bad-shape', message: 'version in the local settings to write must be the number 1' }
  const version = value['version'] as number
  if (version > SETTINGS_KNOWN_VERSION) {
    return {
      ok: false,
      reason: 'version-newer',
      message: 'write refused: these local settings have version ' + version + ', but the core only understands version 1. Writing with an older version would erase new fields; upgrade the plugin before editing.',
    }
  }
  if (version !== SETTINGS_KNOWN_VERSION) return { ok: false, reason: 'bad-shape', message: 'version in the local settings to write must be 1' }
  const check = parseSettings(value)
  if (!check.ok) return { ok: false, reason: check.reason === 'unknown-keys' ? 'unknown-keys' : 'bad-shape', message: check.message, keys: check.keys }
  const v = (check as { ok: true; value: Record<string, unknown> }).value
  const ui = v['ui'] as Record<string, unknown>
  const workspaces = v['workspaces'] as Record<string, Record<string, unknown>>
  const debug = v['debug'] as Record<string, unknown>
  const templates = v['templates'] as Record<string, unknown>

  const lines = [...HEADER]
  lines.push('version: 1')
  lines.push(COMMENT_UI)
  lines.push('ui:')
  lines.push('  ' + COMMENT_STATE)
  lines.push('  stateFilter: ' + esc(String(ui['stateFilter'])))
  lines.push('  sortKey: ' + esc(String(ui['sortKey'])))
  lines.push('  sortDir: ' + esc(String(ui['sortDir'])))
  // labelClicks 不写出去（理由见上面 UI_KEYS 旁的注释）。老文件里那一节在下次写入时自然消失。
  lines.push(COMMENT_WORKSPACES)
  const wsKeys = Object.keys(workspaces)
  if (wsKeys.length === 0) {
    lines.push('workspaces: {}')
  } else {
    lines.push('workspaces:')
    for (const root of wsKeys) {
      const entry = workspaces[root] as Record<string, unknown>
      lines.push('  ' + esc(root) + ':')
      // 临时标记写在记录最前面：它说明这条记录为什么用目录路径当键，读的人该先看到它再看下面几个开关。
      if (entry['unopened'] === true) {
        lines.push('    ' + COMMENT_UNOPENED)
        lines.push('    unopened: true')
      }
      // 五个开关按固定次序写，每个带着自己的注释行；临时记录只写用户真点过的那几格（#1640，缺的格跳过），
      // 普通记录这几格都在（parseSettings 补的），所以照旧全写。
      const fields: Array<[string, string]> = [
        ['statusBar', COMMENT_STATUS_BAR],
        ['deckTools', COMMENT_DECK_TOOLS],
        ['suggest', COMMENT_SUGGEST],
        ['noRepoDismissed', COMMENT_NOREPO],
        ['subwsMarkAutoShown', COMMENT_SUBWS],
      ]
      for (const [name, comment] of fields) {
        const cell = entry[name]
        if (cell === undefined) continue
        lines.push('    ' + comment)
        lines.push('    ' + name + ': ' + (typeof cell === 'string' ? esc(cell) : String(cell)))
      }
    }
  }
  lines.push(COMMENT_DEBUG)
  lines.push('debug:')
  lines.push('  enabled: ' + String(debug['enabled']))
  lines.push('  sampleRate: ' + String(debug['sampleRate']))
  lines.push(COMMENT_TEMPLATES)
  const tplKeys = Object.keys(templates)
  if (tplKeys.length === 0) {
    lines.push('templates: {}')
  } else {
    lines.push('templates:')
    for (const name of tplKeys) lines.push('  ' + esc(name) + ': ' + esc(String(templates[name])))
  }
  return { ok: true, text: lines.join('\n') + '\n' }
}

// ── #1802：跨窗口写设置时的三件纯工具 ──
// 为什么放在核里：它们描述的是「本机设置文档」本身的约定（空文档长什么样、内容指纹怎么算、只带改动格的
//   补丁怎么并进一份文档），宿主写文件那一侧与门禁都读同一份；谁再写一份拷贝就是第二套房。
//   三件都是纯函数，不碰文件系统。

/** 一份「什么都还没设置」的完整设置文档（文件还不存在时，客户端内存里与宿主眼里都按这一份算）。 */
export function settingsEmptyDocument(): Record<string, unknown> {
  return {
    version: 1,
    ui: { stateFilter: '', sortKey: '', sortDir: '', labelClicks: {} },
    workspaces: {},
    debug: { enabled: false, sampleRate: 1 },
    templates: {},
  }
}

/** 把一份值写成「键按字典序排好」的 JSON 文字：同一份内容无论键的先后都得到同一段文字。 */
function canonicalSettingsText(value: unknown): string {
  if (value === null || value === undefined) return 'null'
  if (Array.isArray(value)) return '[' + value.map(canonicalSettingsText).join(',') + ']'
  if (isRecord(value)) {
    const keys = Object.keys(value).sort()
    return '{' + keys.map((k) => JSON.stringify(k) + ':' + canonicalSettingsText(value[k])).join(',') + '}'
  }
  return JSON.stringify(value)
}

/**
 * 设置文档的内容指纹：形如 1a2b3c4d:312（前一段是 32 位散列，后一段是规范化文字的长度）。
 * 用途只有一个：写之前拿它比对「我读到的是不是还是盘上这一份」。它不保密、不防篡改，
 * 只回答「两个窗口读到的是不是同一份内容」。
 */
export function settingsContentHash(value: unknown): string {
  const text = canonicalSettingsText(isRecord(value) ? value : {})
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return ('0000000' + (h >>> 0).toString(16)).slice(-8) + ':' + text.length
}

/** 合并结果：成功时带合并后的整份文档，changed 说明这次真的改动了内容没有。 */
type SettingsMergeResult =
  | { ok: true; value: Record<string, unknown>; changed: boolean }
  | { ok: false; reason: string; message: string; keys?: string[] }

/** 把补丁里的对象并进基底：对象逐键递归，null 表示删掉这个键，其它值直接替换。 */
function mergePatchObject(base: Record<string, unknown>, patch: Record<string, unknown>): { value: Record<string, unknown>; changed: boolean } {
  const next: Record<string, unknown> = { ...base }
  let changed = false
  for (const key of Object.keys(patch)) {
    if (isDangerousKey(key)) throw new Error('this name is not allowed in the patch: ' + key)
    const pv = patch[key]
    if (pv === null) {
      if (Object.prototype.hasOwnProperty.call(next, key)) {
        delete next[key]
        changed = true
      }
      continue
    }
    if (isRecord(pv)) {
      const before = isRecord(next[key]) ? (next[key] as Record<string, unknown>) : {}
      const merged = mergePatchObject(before, pv)
      if (!merged.changed) continue
      next[key] = merged.value
      changed = true
      continue
    }
    if (canonicalSettingsText(next[key]) !== canonicalSettingsText(pv)) {
      next[key] = pv
      changed = true
    }
  }
  return { value: next, changed }
}

/**
 * 把「只含改动的格」的补丁并进一份最新读到的设置文档（#1802）。
 * 补丁的形状与设置文档同构：例如 { workspaces: { 'D:/proj': { statusBar: 'hide' } } }；
 * 值为 null 表示把这个键删掉（临时记录搬到正式键上时用它清掉旧的那一条）。
 * 合并完再按读同一套规矩校验一遍 —— 补丁里若出现核不认识的名字或坏值，整份拒绝，一个格都不改。
 */
export function mergeSettingsPatch(base: unknown, patch: unknown): SettingsMergeResult {
  if (!isRecord(patch)) return { ok: false, reason: 'bad-shape', message: 'this save has no fields to change (the patch must be a name-to-value mapping)' }
  const strangeTop = unknownIn(patch, TOP_KEYS)
  if (strangeTop.length > 0) return { ok: false, reason: 'unknown-keys', message: 'this save changes fields unknown to the core: ' + strangeTop.join(', '), keys: strangeTop }
  const start = isRecord(base) ? base : settingsEmptyDocument()
  let merged: { value: Record<string, unknown>; changed: boolean }
  try {
    merged = mergePatchObject(start, patch)
  } catch (e) {
    return { ok: false, reason: 'bad-shape', message: String((e && (e as Error).message) || e || 'the patch contains disallowed names') }
  }
  const changed = merged.changed || canonicalSettingsText(start) !== canonicalSettingsText(merged.value)
  const check = parseSettings(merged.value)
  if (!check.ok) {
    const bad = check as { ok: false; reason: string; message: string; keys?: string[] }
    const reason = bad.reason === 'unknown-keys' ? 'unknown-keys' : 'bad-shape'
    return { ok: false, reason: reason, message: bad.message, keys: bad.keys }
  }
  return { ok: true, value: (check as { ok: true; value: Record<string, unknown> }).value, changed }
}
