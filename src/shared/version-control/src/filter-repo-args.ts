/**
 * filter-repo 的参数语法：只接受面板五张表单需要的选项，开关与带值选项分开认。
 * 为什么不能「凡是短横线开头就放行」：这等于把通道做成通用执行器，第三方工具能收的选项里
 * 有改远端、改配置一类破坏性开关，面板必须只放自己算得清的参数。带值选项的值在这里再校验一遍，
 * 因为任务通道是独立入口，不能假设调用方（宿主写层）一定校验过。
 */
export function filterRepoArgs(input: any): any {
  if (!Array.isArray(input)) return { ok: false, reason: 'bad-args', message: 'external tool arguments must be an array' }
  const switches: string[] = ['--invert-paths', '--replace-refs']
  const relativeValued: string[] = ['--path']
  const renameValued: string[] = ['--path-rename']
  const thresholdValued: string[] = ['--strip-blobs-bigger-than']
  const fileValued: string[] = ['--mailmap', '--replace-text']
  const out: string[] = []
  for (let i = 0; i < input.length; i += 1) {
    const item: any = input[i]
    if (typeof item !== 'string' || item.length === 0 || item.charAt(0) !== '-') return { ok: false, reason: 'bad-args', message: 'external tool arguments accept only registered options', hint: 'options must start with a hyphen and be on the allowlist' }
    if (switches.indexOf(item) >= 0) { out.push(item); continue }
    const valued: boolean = relativeValued.indexOf(item) >= 0 || renameValued.indexOf(item) >= 0 || thresholdValued.indexOf(item) >= 0 || fileValued.indexOf(item) >= 0
    if (!valued) return { ok: false, reason: 'bad-args', message: 'external tool arguments accept only registered options', hint: 'this option is not on the allowlist' }
    const value: any = input[i + 1]
    if (typeof value !== 'string' || value.length === 0) return { ok: false, reason: 'bad-args', message: 'an option that takes a value must be followed by a nonempty value', hint: 'check whether ' + item + ' is missing its value' }
    if (relativeValued.indexOf(item) >= 0) {
      const problem: any = relativeRepoPathProblem(value)
      if (problem) return { ok: false, reason: 'bad-path', message: problem, hint: 'use repository-relative paths with forward slashes, without .., backslashes or drive letters' }
    } else if (renameValued.indexOf(item) >= 0) {
      const cut: number = value.indexOf(':')
      if (cut <= 0 || cut >= value.length - 1) return { ok: false, reason: 'bad-path', message: 'write a rename as old-path:new-path', hint: 'separate with an ASCII colon; both sides are repository-relative paths' }
      const fromProblem: any = relativeRepoPathProblem(value.slice(0, cut))
      const toProblem: any = relativeRepoPathProblem(value.slice(cut + 1))
      if (fromProblem || toProblem) return { ok: false, reason: 'bad-path', message: 'rename source or target is not a valid repository-relative path', hint: 'both sides must be relative paths, without .., backslashes or drive letters' }
    } else if (thresholdValued.indexOf(item) >= 0) {
      if (!/^[1-9][0-9]{0,6}[kKmMgG]?$/.test(value)) return { ok: false, reason: 'bad-args', message: 'size threshold must be a positive integer with a unit, such as 10M, 500k or 1G', hint: 'without a unit, the value is in bytes' }
    } else {
      const fileProblem: any = materialFileProblem(value)
      if (fileProblem) return { ok: false, reason: 'bad-path', message: fileProblem, hint: 'these two options only accept absolute paths to regular files (temporary instruction files generated by the panel)' }
    }
    out.push(item)
    out.push(value)
    i += 1
  }
  return { ok: true, args: out }
}

/** 仓库内相对路径的守卫：只放普通相对路径，挡掉绝对路径、反斜杠、.. 段与控制字符。 */
function relativeRepoPathProblem(path: any): string | null {
  if (typeof path !== 'string' || path.length === 0) return 'path is empty'
  if (path.length > 1024) return 'path is too long'
  if (/^[A-Za-z]:/.test(path) || path.charAt(0) === '/' || path.charAt(0) === '\\') return 'path must be relative, not absolute'
  if (path.indexOf('\\') >= 0) return 'path must use forward slashes'
  if (/[\u0000-\u001f]/.test(path)) return 'path contains control characters'
  const parts: string[] = path.split('/')
  for (const part of parts) { if (part === '..' || part === '.') return 'path cannot contain . or .. segments' }
  return null
}

/** 临时说明文件的守卫：只接受绝对路径（面板写在系统临时目录里），挡掉 .. 段与控制字符。 */
function materialFileProblem(path: any): string | null {
  if (typeof path !== 'string' || path.length === 0) return 'file path is empty'
  if (path.length > 4096) return 'file path is too long'
  if (/[\u0000\u001f]/.test(path)) return 'file path contains control characters'
  const absolute: boolean = /^[A-Za-z]:[\\/]/.test(path) || path.charAt(0) === '/'
  if (!absolute) return 'file path must be absolute'
  if (path.indexOf('..') >= 0) return 'file path cannot contain .. segments'
  return null
}
